import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync, readFileSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {createWorkspaceStore} from '../lib/workspace.mjs';

test('goal trash is reversible, survives restart and retains descendants and measurements', t => {
  const dir = mkdtempSync(path.join(tmpdir(), 'iw-goal-trash-'));
  t.after(() => rmSync(dir, {recursive: true, force: true}));
  const file = path.join(dir, 'workspace.json');
  const portfolio = () => ({projects: [], alphas: [], tasks: []});
  const store = createWorkspaceStore(file, portfolio);
  const root = store.mutate('saveGoal', {title: 'Родитель', unit: 'шт', direction: 'up', status: 'active'}).goals[0];
  store.mutate('saveGoal', {title: 'Подцель', unit: 'шт', direction: 'up', status: 'ready', parentId: root.id});
  store.mutate('measure', {kind: 'goal', targetId: root.id, date: '2026-10-26', value: 0, evidence: 'Исходный замер'});
  const before = structuredClone(store.view());
  const at = '2026-10-26T18:00:00.000Z';
  const command = {requestId: randomUUID(), action: 'saveGoal', input: {...root, trashedAt: at}, expectedUpdatedAt: root.updatedAt};
  store.nativeMutate(command);
  const deleted = store.view().goals.find(g => g.id === root.id);
  assert.equal(deleted.trashedAt, at);
  const snapshot = readFileSync(file, 'utf8');
  store.nativeMutate(command);
  assert.equal(readFileSync(file, 'utf8'), snapshot);
  assert.throws(() => store.nativeMutate({...command, requestId: randomUUID(), expectedUpdatedAt: 'wrong'}), /изменились/);
  assert.equal(readFileSync(file, 'utf8'), snapshot);
  const reopened = createWorkspaceStore(file, portfolio);
  assert.equal(reopened.view().goalTrashVersion, 1);
  assert.equal(reopened.view().goals.find(g => g.id === root.id).trashedAt, at);
  reopened.nativeMutate({requestId: randomUUID(), action: 'saveGoal', input: {...deleted, trashedAt: null}, expectedUpdatedAt: deleted.updatedAt});
  assert.equal(reopened.view().goals.find(g => g.id === root.id).trashedAt, null);
  assert.deepEqual(reopened.view().measurements, before.measurements);
  assert.equal(reopened.view().goals.find(g => g.parentId === root.id).status, 'ready');
  const restored = readFileSync(file, 'utf8');
  assert.throws(() => reopened.mutate('saveGoal', {...deleted, trashedAt: 'bad'}), /дата/);
  assert.equal(readFileSync(file, 'utf8'), restored);
});
