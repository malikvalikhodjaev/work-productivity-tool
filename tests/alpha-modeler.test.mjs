import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createStore } from '../lib/store.mjs';
import { writeLegacyAlphaFixture } from './alpha-fixture.mjs';

const fixture = () => { const file = path.join(mkdtempSync(path.join(tmpdir(),'alpha-modeler-')),'dashboard.json'); writeLegacyAlphaFixture(file); return {file,store:createStore(file)}; };
test('Просмотр и сохранение без правок не меняют файл; заметки, детали V2 и история переживают повторный запуск', () => {
  const {file,store} = fixture(); const alpha = store.getPortfolio().alphas[0]; const original = readFileSync(file,'utf8');
  store.getPortfolio(); store.alphaHistory(alpha.id); store.alphaBackup();
  store.updatePortfolio('updateAlpha',{...alpha,expectedRevision:0});
  assert.equal(readFileSync(file,'utf8'),original);
  const input = {...alpha,description:'Моя новая заметка\nсо второй строкой',evidence:'Пока неизвестно',nextStep:'Проверить потребность',reviewDate:'2026-10-07',whyImportant:'Польза клиенту',adaptedAlpha:'Клиенты проекта',area:'Надсистема',source:'Мой справочник',metaAdaptation:'Конкретизация',systemTime:'Оба',attention:'Проверить позже',expectedRevision:0};
  const result = store.updatePortfolio('updateAlpha',input);
  const changed = result.alphas.find(item=>item.id===alpha.id);
  assert.equal(changed.revision,1); assert.equal(changed.reviewDate,'2026-10-07');
  assert.equal(store.alphaHistory(alpha.id).length,2);
  const saved = readFileSync(file,'utf8');
  store.updatePortfolio('updateAlpha',{...changed,expectedRevision:1});
  assert.equal(readFileSync(file,'utf8'),saved);
  const reopened = createStore(file); assert.equal(reopened.getPortfolio().alphas[0].description,input.description);
  assert.equal(reopened.alphaHistory(alpha.id)[0].snapshot.description,alpha.description);
  assert.equal(reopened.alphaHistory(alpha.id)[1].snapshot.description,input.description);
  assert.deepEqual(reopened.getWeek('2026-10-05').entries,[]);
});
test('Запись только с именем разрешена; другая вкладка не перезаписывает правки, старая форма сохраняет новые поля', () => {
  const {file,store} = fixture();
  const result = store.updatePortfolio('createAlpha',{projectId:'test-project',zoneId:'customers',uniqueName:'Новый конкретный объект',state:'empty',description:'Начальная заметка'});
  const alpha = result.alphas.at(-1); assert.equal(alpha.typeName,''); assert.equal(alpha.filledDate,null);
  store.updatePortfolio('updateAlpha',{...alpha,expectedRevision:1,reviewDate:'2026-10-08',whyImportant:'Пользовательский интерес'});
  const after = readFileSync(file,'utf8');
  assert.throws(()=>store.updatePortfolio('updateAlpha',{...alpha,expectedRevision:1,description:'Устаревшая вкладка'}),/другой вкладке/);
  assert.equal(readFileSync(file,'utf8'),after);
  const oldForm = {...store.getPortfolio().alphas.at(-1),description:'Правка из Workflow'};
  delete oldForm.reviewDate; delete oldForm.whyImportant;
  store.updatePortfolio('updateAlpha',oldForm);
  assert.equal(store.getPortfolio().alphas.at(-1).reviewDate,'2026-10-08');
  assert.equal(store.getPortfolio().alphas.at(-1).whyImportant,'Пользовательский интерес');
});
