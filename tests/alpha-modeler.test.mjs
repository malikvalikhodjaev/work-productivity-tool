test('Перенос проекта и его истории не меняет нормы и часы получателя', () => {
  const source=fixture(); const destination=fixture();
  source.store.updatePortfolio('createProject',{name:'Свой проект',status:'active',phase:'pre_operation',zoneIds:['customers']});
  const project=source.store.getPortfolio().projects.at(-1);
  source.store.updatePortfolio('createAlpha',{projectId:project.id,zoneId:'customers',uniqueName:'Объект своего проекта',state:'empty',description:'Первая версия'});
  const alpha=source.store.getPortfolio().alphas.at(-1);
  source.store.updatePortfolio('updateAlpha',{...alpha,description:'Вторая версия',expectedRevision:1});
  destination.store.updateTargets('2026-10-05',{reading:12});
  destination.store.addEntry({metricId:'reading',date:'2026-10-06',amount:1,title:'Свой учёт'});
  const before=destination.store.getWeek('2026-10-05'); const backup=source.store.alphaBackup();
  destination.store.importAlphas(backup,true);
  assert.equal(destination.store.getPortfolio().projects.at(-1).name,'Свой проект');
  assert.ok(destination.store.alphaHistory(alpha.id).some(entry=>entry.snapshot.description==='Первая версия'));
  assert.ok(destination.store.alphaHistory(alpha.id).some(entry=>entry.snapshot.description==='Вторая версия'));
  assert.deepEqual(destination.store.getWeek('2026-10-05').metrics,before.metrics);
  assert.deepEqual(destination.store.getWeek('2026-10-05').entries,before.entries);
});
